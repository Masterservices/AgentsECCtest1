#!/usr/bin/env python3
"""Publie le résultat d'une demande traitée par Claude dans la GitHub Action « Demandes Dialagram ».

Lit travail/resultat.json et travail/reponse.md, commente l'issue, ajoute la fiche technique
(<!-- meta … -->) au corps de l'issue, met l'étiquette d'état et ferme la demande si elle est terminée.
Variables : NUM (numéro de l'issue), GITHUB_REPOSITORY, GH_TOKEN (utilisé par la commande gh).
"""
import json
import os
import subprocess
import sys

NUM = os.environ["NUM"]
REPO = os.environ["GITHUB_REPOSITORY"]
SIGNATURE = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n"


def gh(*args, entree=None):
    return subprocess.run(["gh", *args, "--repo", REPO], input=entree, text=True, capture_output=True, check=False)


def etiquettes(etat):
    # une commande par étiquette : retirer une étiquette absente ne doit pas bloquer les autres changements
    for retirer in ("en-cours", "a-faire"):
        if retirer != etat:
            gh("issue", "edit", NUM, "--remove-label", retirer)
    gh("issue", "edit", NUM, "--add-label", "dialagram", "--add-label", etat)


def main():
    try:
        r = json.load(open("travail/resultat.json", encoding="utf-8"))
    except (OSError, ValueError):
        gh("issue", "comment", NUM, "--body-file", "-",
           entree="La demande n'a pas pu être traitée automatiquement cette fois ; elle reste en file et sera reprise." + SIGNATURE)
        etiquettes("a-faire")
        return 1

    statut = r.get("statut")
    if statut == "refuse":
        gh("issue", "comment", NUM, "--body-file", "-",
           entree=f"**Demande non traitée.** {r.get('evaluation', '')}" + SIGNATURE)
        etiquettes("refuse")
        gh("issue", "close", NUM, "--reason", "not planned")
        return 0
    if statut == "livre":
        gh("issue", "comment", NUM, "--body-file", "-", entree=f"**Livre en préparation.** {r.get('evaluation', '')}" + SIGNATURE)
        gh("issue", "edit", NUM, "--add-label", "livre")
        return 0

    reponse = open("travail/reponse.md", encoding="utf-8").read().strip()
    modele = r.get("modele", "")
    corps = (f"**Note de Claude : {r.get('note', '?')} (validé).** {r.get('evaluation', '')}\n\n"
             f"_Réponse rédigée par {modele} via Dialagram, relue et corrigée par Claude._\n\n---\n\n{reponse}" + SIGNATURE)
    gh("issue", "comment", NUM, "--body-file", "-", entree=corps)

    meta = {k: r[k] for k in ("modele", "tokens", "secondes", "claude_tokens", "note") if k in r}
    meta["claude_estime"] = True
    actuel = gh("issue", "view", NUM, "--json", "body", "--jq", ".body").stdout.rstrip()
    gh("issue", "edit", NUM, "--body-file", "-", entree=f"{actuel}\n\n<!-- meta {json.dumps(meta, ensure_ascii=False)} -->\n")
    etiquettes("valide")
    gh("issue", "close", NUM, "--reason", "completed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
